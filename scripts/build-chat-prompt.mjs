#!/usr/bin/env node
// Regenerates server/generated/chatPrompt.generated.ts from chat/system-prompt.md
// and chat/facts.md.
//
// Runs automatically before `npm run build` and `npm run dev` (see the
// "prebuild"/"predev" scripts in package.json — npm invokes these
// lifecycle hooks on its own, no extra CI config needed, so Vercel's
// `npm run build` picks this up for free).
//
// Edit the prompt or the facts in chat/, never in
// server/generated/chatPrompt.generated.ts directly — it's overwritten
// every run. The output is gitignored; only the chat/*.md sources are
// committed.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const sysPath = join(root, 'chat', 'system-prompt.md');
const factsPath = join(root, 'chat', 'facts.md');
const outDir = join(root, 'server', 'generated');
const outPath = join(outDir, 'chatPrompt.generated.ts');

const sys = readFileSync(sysPath, 'utf8');
const facts = readFileSync(factsPath, 'utf8');
const combined = `${sys}\n\n---\n\n${facts}`;

const out =
  '// AUTO-GENERATED by scripts/build-chat-prompt.mjs from chat/system-prompt.md\n' +
  '// and chat/facts.md. Do not edit this file directly — edit the sources and\n' +
  '// re-run `npm run build-chat-prompt`, or just build/dev normally (this runs\n' +
  '// automatically via the prebuild/predev npm hooks).\n' +
  `export const SYSTEM_PROMPT = ${JSON.stringify(combined)};\n`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${out.length} bytes)`);
